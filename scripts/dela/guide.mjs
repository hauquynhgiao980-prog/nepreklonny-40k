const open = { intro: true, cells: true };

function htmlBlock(html) { const d = h("div.nk-g-text"); d.innerHTML = html; return d; }

function section(key, title, kids, extra = null) {
  const on = open[key] !== false;
  return h("section", { class: `nk-g-sec ${on ? "on" : ""}`, "data-sec": key },
    h("div.nk-g-head", {},
      h("button.nk-g-tog", { onclick: e => { open[key] = open[key] === false; const b = e.currentTarget; b.closest(".nk-g-sec").classList.toggle("on", open[key]); b.textContent = `${open[key] ? "▾" : "▸"} ${title}`; } }, `${on ? "▾" : "▸"} ${title}`),
      h("div", { style: "flex:1" }), extra),
    h("div.nk-g-body", {}, kids));
}

/** Вкладка «Сценарий». */
export function guideTab(rerender) {
  const out = [section("intro", "О МОДУЛЕ · КТО, ЧТО, ЗАЧЕМ", htmlBlock(INTRO))];
  for (const L of LOCATIONS) {
    const sc = game.scenes?.find?.(s => s.flags?.[S.MOD]?.scene === L.scene);
    const view = sc ? h("button.nk-btn.small", { title: "Открыть сцену у себя", onclick: e => { e.stopPropagation(); sc.view(); } }, "СМОТРЕТЬ СЦЕНУ") : null;
    out.push(section(L.key, L.title, [...(L.tools || []).map(t => t(rerender)), htmlBlock(L.html)], view));
  }
  out.push(h("div.nk-g-hint", { style: "margin-top:14px" }, "Остальные локации добавим по порядку: пост охраны, зал этапа, шлюпочная палуба, полное описание галереи."));
  return out;
}
